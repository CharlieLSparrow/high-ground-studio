def build_packet(args: argparse.Namespace) -> dict[str, Any]:
    manifest_path = resolve_manifest_path(args)
    manifest = load_json(manifest_path) if manifest_path and manifest_path.exists() else {}
    candidates = dict_list(manifest.get("candidates"))
    rows = [validate_candidate(candidate) for candidate in candidates]
    counts = counts_for(rows)
    status = "episode4-found-clip-validation-ready" if rows else "episode4-found-clip-validation-empty"
    if counts["readyForSourceIntakeReview"]:
        next_action = "Run episode4-source-clip-intake, then review cue matches before any clip-weave promotion."
    elif counts["waitingForFile"]:
        next_action = "Recover watched/source files or fill candidateFilePath values, then rerun this validation."
    else:
        next_action = "Fix manifest rows or regenerate the watched/source recovery packet."
    return {
        "schema": SCHEMA,
        "generatedAt": iso_now(),
        "status": status,
        "episode": "episode-4",
        "manifestPath": str(manifest_path) if manifest_path else "",
        "manifestExists": manifest_path.exists() if manifest_path else False,
        "rows": rows,
        "counts": counts,
        "nextSafestAction": next_action,
        "truth": truth(),
    }


def write_packet(packet: dict[str, Any]) -> dict[str, Any]:
    session_dir = OUT_ROOT / stamp()
    session_dir.mkdir(parents=True, exist_ok=True)
    json_path = session_dir / "episode4-found-clip-manifest-validation.json"
    markdown_path = session_dir / "episode4-found-clip-manifest-validation.md"
    html_path = session_dir / "index.html"
    packet.update({"sessionDir": str(session_dir), "jsonPath": str(json_path), "markdownPath": str(markdown_path), "htmlPath": str(html_path)})
    write_json(json_path, packet)
    markdown_path.write_text(render_markdown(packet), encoding="utf-8")
    html_path.write_text(render_html(packet), encoding="utf-8")
    write_json(
        LATEST_POINTER,
        {
            "schema": SCHEMA + ".pointer",
            "generatedAt": iso_now(),
            "status": packet.get("status"),
            "sessionDir": str(session_dir),
            "jsonPath": str(json_path),
            "markdownPath": str(markdown_path),
            "htmlPath": str(html_path),
            "manifestPath": packet.get("manifestPath"),
            "counts": packet.get("counts"),
            "nextSafestAction": packet.get("nextSafestAction"),
            "truth": packet.get("truth"),
        },
    )
    return packet


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, help="Editable found-clip manifest JSON to validate.")
    parser.add_argument("--recovery-pointer", type=Path, default=RECOVERY_POINTER)
    parser.add_argument("--json", action="store_true", help="Print JSON. This is the default.")
    parser.add_argument("--markdown", action="store_true", help="Print Markdown.")
    args = parser.parse_args()
    packet = write_packet(build_packet(args))
    if args.markdown:
        print(render_markdown(packet))
    else:
        print(json.dumps(packet, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
