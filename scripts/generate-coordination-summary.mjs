import fs from 'node:fs';
import path from 'node:path';

const REPORTS_DIR = path.join(process.cwd(), 'docs', 'coordination', 'antigravity-reports');
const OUTPUT_PATH = path.join(process.cwd(), 'docs', 'coordination', 'FLOCK-SUMMARY.md');

const ALLOWED_LANES = new Set([
  'AG-Editor-Spine',
  'AG-Assistant',
  'AG-Research-RAG',
  'AG-Video-Editor',
  'AG-Storyboard',
  'AG-Project-Management',
  'AG-Marketing',
  'AG-Patreon-Support',
  'AG-Mobile-Recording',
  'AG-Agent-Coordination',
  'AG-HighGroundOdyssey',
  'AG-QuipLore',
  'AG-Fiction-Analysis',
  'AG-Publishing-Integrations',
  'AG-Scroll-Experiences',
  'AG-Release-Captain'
]);

function extractLatestReport(content, fileName) {
  const lines = content.split('\n');
  const reports = [];
  let currentReport = null;

  for (const line of lines) {
    const match = line.match(/^## (\d{4}-\d{2}-\d{2} \d{2}:\d{2}) local - (AG-[\w-]+)/);
    if (match) {
      if (currentReport) {
        reports.push(currentReport);
      }
      currentReport = {
        timestamp: match[1],
        lane: match[2],
        content: [line],
        file: fileName
      };
    } else if (currentReport && !line.match(/^## 202\d-/)) {
      currentReport.content.push(line);
    }
  }
  
  if (currentReport) {
    reports.push(currentReport);
  }

  // Return the report with the latest timestamp
  if (reports.length === 0) return null;
  reports.sort((a, b) => b.timestamp.localeCompare(a.timestamp));
  return reports[0];
}

async function run() {
  if (!fs.existsSync(REPORTS_DIR)) {
    console.error(`❌ ERROR: Reports directory not found at ${REPORTS_DIR}`);
    process.exit(1);
  }

  console.log('🦅 Generating Flock Summary...');
  const files = fs.readdirSync(REPORTS_DIR).filter(f => f.endsWith('.md'));
  
  let allLatestReports = [];

  for (const file of files) {
    const content = fs.readFileSync(path.join(REPORTS_DIR, file), 'utf-8');
    const latest = extractLatestReport(content, file);
    if (latest && ALLOWED_LANES.has(latest.lane)) {
      allLatestReports.push(latest);
    }
  }

  // Sort all reports across all agents by most recent
  allLatestReports.sort((a, b) => b.timestamp.localeCompare(a.timestamp));

  let outputLines = [
    '# 🦅 Antigravity Flock Summary',
    '',
    `*Generated on: ${new Date().toISOString()}*`,
    '',
    '> **Release Captain (Codex):** This file is auto-generated by `scripts/generate-coordination-summary.mjs`. It aggregates the single most recent execution report from every active lane into one chronological dashboard.',
    ''
  ];

  for (const rep of allLatestReports) {
    outputLines.push('---');
    outputLines.push('');
    // Join the content and clean up extra newlines at the end
    let joined = rep.content.join('\n').trim();
    outputLines.push(joined);
    outputLines.push('');
  }

  fs.writeFileSync(OUTPUT_PATH, outputLines.join('\n'), 'utf-8');
  console.log(`✅ Flock Summary generated at docs/coordination/FLOCK-SUMMARY.md`);
  console.log(`   Captured ${allLatestReports.length} lane reports.`);
}

run();
